"""Runs the whole evaluation and writes RESULTS.md and results.json.

  T2: seeded synthetic logs (several seeds, results added up)
  T4: attacker-change tests: every attack kind x every mutation, many random variants each
(T3, a public log, is scored separately by public.py.)
"""
import json
import random
from pathlib import Path

from cloudtrace import __version__
from cloudtrace.evaluation import (
    check2_cost,
    delay,
    detectors,
    generator,
    metrics,
    mutations,
    scenarios,
    sensitivity,
)

LABELS = {"ct": "CloudTrace (medium+)", "ct_any": "CloudTrace (any finding)", "b1": "B1 Sigma",
          "b2": "B2 Elastic cross-user", "b2x": "B2 + approved roles excluded",
          "b3": "B3 Elastic self-key used"}
DEFAULT_SEEDS = (1, 2, 3, 4, 5)
VARIANTS = 20


def run_t2(seeds=DEFAULT_SEEDS) -> dict:
    per_seed = []
    for seed in seeds:
        records, scs = generator.generate(seed)
        per_seed.append(metrics.score_t2(records, scs, detectors.run_all(records)))
    pooled = metrics.pool(per_seed)
    pooled["seed_list"] = list(seeds)
    return pooled


def run_t4(variants: int = VARIANTS) -> dict:
    cells = {}
    for m, kinds in mutations.APPLIES.items():
        for kind in kinds:
            caught = dict.fromkeys(mutations.DETECTORS, 0)
            raw = dict.fromkeys(mutations.DETECTORS, 0)
            unknown = 0
            for v in range(variants):
                rng = random.Random(f"{m}-{kind}-{v}")
                alloc = scenarios.Allocator(rng)
                log = scenarios.Log(prefix=f"t4{m}{v}")
                t0 = scenarios.BASE_TIME + scenarios.timedelta(days=1)
                sc = scenarios.build(kind, log, rng, alloc, t0, mutations.build_opts(rng, m),
                                     sid=f"{m}-{kind}-{v}")
                records = sorted(log.records, key=lambda r: r["eventTime"])
                records = mutations.post_process(records, m, rng)
                det = detectors.run_all(records)
                chain = set(sc.event_ids)
                for d in mutations.DETECTORS:
                    caught[d] += bool(det[d]["events"] & chain)
                    raw[d] += det[d]["raw_alerts"]
                if not (det["ct"]["events"] & chain) and any(
                        r["verdict"] == "NOT_CHECKED" and r["event_id"] in chain
                        for r in det["_rows"]):
                    unknown += 1
            predicted = mutations.PREDICTIONS[(m, kind)]
            cells[f"{m}|{kind}"] = {
                "mutation": m, "kind": kind, "variants": variants, "caught": caught,
                "alerts_per_variant": {d: round(raw[d] / variants, 2) for d in raw},
                "ct_not_checked_when_missed": unknown,
                "predicted": predicted,
                "matches_prediction": {
                    d: caught[d] == (variants if predicted[d] else 0) for d in mutations.DETECTORS},
            }
    return cells


def _pct(x):
    return "n/a" if x is None else f"{round(100 * x)}%"


INTRO = (
    "All data is synthetic. Ground truth comes from the generator, not from any detector. "
    "These numbers describe this synthetic test set only; they are not a claim about real "
    "networks.")
T2_HEAD = (
    "| Detector | Attacks caught (in scope) | Recall (in scope) | Self-made-key attacks caught "
    "(out of CloudTrace scope) | Benign scenarios flagged | Precision | False alarms per "
    "1,000 normal events | Events to review |")
HONEST = [
    "- Scenario mix and the share of look-alike benign cases are our assumptions.",
    ("- B1, B2 and B3 are re-implementations of the published rule logic, replayed on a whole "
     "file. Live scheduling details (look-back time, alert caps) are not modelled."),
    ("- B3 is built for self-made keys, so it is expected to miss cross-identity attacks; "
     "CloudTrace is expected to miss self-made-key attacks (outside its stated scope)."),
    ("- 'CloudTrace (medium+)' counts only findings of score 3 or more; a Check 1 note alone "
     "(score 1) is shown in the 'any finding' row."),
    ("- Attacks here are built to resemble the patterns the checks look for, so high recall on "
     "them proves the code works as designed, not that it finds real attacks. Real-log testing "
     "(T3) is reported separately in results/public/RESULTS_T3.md."),
]


def render(t2: dict, t4: dict) -> str:
    cols = mutations.DETECTORS
    head = "| " + " | ".join(LABELS[d] for d in cols) + " |"
    rule = "|---|" + "---|" * len(cols)
    out = ["# CloudTrace evaluation results", "",
           (f"Tool version {__version__}. Generated by `cloudtrace evaluate` "
            f"(seeds {t2['seed_list']}, {VARIANTS} variants per attacker-change cell)."), "",
           INTRO, "",
           "## T2: generated logs (all seeds added up)", "",
           T2_HEAD, "|---|---|---|---|---|---|---|---|"]
    for d in cols:
        r = t2[d]
        lo, hi = r["recall_in_scope_range"]
        out.append(
            f"| {LABELS[d]} | {r['tp_in_scope']}/{r['n_in_scope']} | "
            f"{_pct(r['recall_in_scope'])} (per seed {_pct(lo)}-{_pct(hi)}) | "
            f"{r['tp_out_of_scope']}/{r['n_out_of_scope']} | "
            f"{r['fp_scenarios']}/{r['n_benign']} | {_pct(r['precision'])} | "
            f"{r['false_alarms_per_1000_normal_events']} | {r['alert_events']} |")
    x = t2["extras"]
    out += ["",
            (f"CloudTrace could not check {x['ct_in_scope_attacks_not_checked']} in-scope attack "
             "scenario(s) and said so (NOT_CHECKED) instead of guessing. "
             f"B1 alerted on {x['b1_alerts_on_normal_events']} normal events; for "
             f"{x['of_those_ct_gave_a_reason']} of them CloudTrace recorded an explicit reason "
             "(ignored or not checked)."), "",
            "### Which scenarios each detector flagged (flagged/total)", "",
            "| Scenario kind " + head, rule]
    for kind in scenarios.ALL_KINDS:
        row = [f"{t2[d]['by_kind'][kind][0]}/{t2[d]['by_kind'][kind][1]}" for d in cols]
        out.append(f"| {kind} | " + " | ".join(row) + " |")

    out += ["", "## T4: attacker-change tests", "",
            (f"Each cell: variants caught out of {VARIANTS}. (!) means the measured result "
             "differs from the prediction written before the run (see docs/EVALUATION.md)."), ""]
    mismatches = []
    for kind in scenarios.ATTACK_KINDS:
        out += [f"### {kind}", "",
                "| Change " + head[:-1] + "| CloudTrace not-checked |",
                rule + "---|"]
        for m in mutations.NAMES:
            cell = t4.get(f"{m}|{kind}")
            if not cell:
                continue
            row = []
            for d in cols:
                mark = "" if cell["matches_prediction"][d] else " (!)"
                if mark:
                    mismatches.append((m, kind, d, cell["caught"][d], cell["variants"],
                                       cell["predicted"][d]))
                text = f"{cell['caught'][d]}/{cell['variants']}{mark}"
                if m == "M5" and cell["caught"][d]:
                    text += f" ({cell['alerts_per_variant'][d]} alerts each)"
                row.append(text)
            out.append(f"| {m} {mutations.NAMES[m]} | " + " | ".join(row)
                       + f" | {cell['ct_not_checked_when_missed']} |")
        out.append("")
    out += ["### Differences from our predictions", ""]
    if mismatches:
        for m, kind, d, got, n, pred in mismatches:
            out.append(f"- {m} on {kind}, {LABELS[d]}: predicted "
                       f"{'caught' if pred else 'missed'}, measured {got}/{n}.")
    else:
        out.append("None: every measured cell matched the prediction written beforehand.")
    out += ["", "## Reading these results honestly", ""] + HONEST + [""]
    return "\n".join(out)


def run_all(out_dir, seeds=DEFAULT_SEEDS, variants: int = VARIANTS) -> dict:
    t2 = run_t2(seeds)
    t4 = run_t4(variants)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "results.json").write_text(json.dumps({"t2": t2, "t4": t4}, indent=2) + "\n",
                                      encoding="utf-8")
    (out / "RESULTS.md").write_text(render(t2, t4), encoding="utf-8")
    (out / "SENSITIVITY.md").write_text(sensitivity.render(sensitivity.run_sensitivity(seeds)),
                                        encoding="utf-8")
    (out / "DELAY.md").write_text(delay.render(delay.run_delay(variants)), encoding="utf-8")
    (out / "CHECK2_COST.md").write_text(check2_cost.render(check2_cost.run_cost(seeds)),
                                        encoding="utf-8")
    return {"t2": t2, "t4": t4}
